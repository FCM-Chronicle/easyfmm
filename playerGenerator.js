    function hashString32(str) {
        let h = 2166136261;
        const s = String(str || 'player');
        for (let i = 0; i < s.length; i++) {
            h ^= s.charCodeAt(i);
            h = Math.imul(h, 16777619);
        }
        return h >>> 0;
    }

