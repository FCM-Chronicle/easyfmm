    function pickCountry(options = {}) {
        const { clubCountry = null, teamKey = null, localWeight = 0.55 } = options;
        const homeCountry = normalizeCountry(clubCountry) || getClubCountry(teamKey);
        if (homeCountry && COUNTRY_TO_POOL[homeCountry] && Math.random() < localWeight) {
            return homeCountry;
        }
        return pickWeighted(WEIGHTED_INTERNATIONAL_COUNTRIES).country;
    }

    function collectExistingNames(extraNames = null) {
        const names = new Set();

        const addList = (list) => {
            if (!Array.isArray(list)) return;
            for (const p of list) {
                if (p && p.name) names.add(p.name);
            }
        };

        if (typeof teams !== 'undefined' && teams) {
            Object.values(teams).forEach(addList);
        }
        if (typeof allTeams !== 'undefined' && allTeams) {
            Object.values(allTeams).forEach(t => t && addList(t.players));
        }
        if (typeof gameData !== 'undefined' && gameData) {
            addList(gameData.youthSquad);
            if (gameData.aiPrestige && typeof gameData.aiPrestige === 'object') {
                Object.values(gameData.aiPrestige).forEach(arr => {
                    if (Array.isArray(arr)) arr.forEach(n => typeof n === 'string' && names.add(n));
                });
            }
        }
        if (typeof transferSystem !== 'undefined' && transferSystem) {
            addList(transferSystem.transferMarket);
            addList(transferSystem.extraPlayers);
        }
        if (typeof WorldCupManager !== 'undefined' && WorldCupManager) {
            if (WorldCupManager.wcPlayers) Object.values(WorldCupManager.wcPlayers).forEach(addList);
            if (WorldCupManager.nationalPools) Object.values(WorldCupManager.nationalPools).forEach(addList);
        }

        if (extraNames) {
            if (extraNames instanceof Set || Array.isArray(extraNames)) {
                for (const n of extraNames) {
                    if (typeof n === 'string' && n) names.add(n);
                    else if (n && n.name) names.add(n.name);
                }
            }
        }
        return names;
    }

    function generateKoreanName() {
        const roll = Math.random();
        if (roll >= 0.95) {
            const topSurnames = ['김', '이', '박', '최', '정', '강', '조', '윤', '장', '임', '한', '송', '홍'];
            return `${pick(topSurnames)}${pick(KOREAN_SINGLE_GIVEN)}`;
        }

        const surname = Math.random() < 0.012
            ? pick(KOREAN_RARE_COMPOUND_SURNAMES)
            : pick(KOREAN_COMMON_SURNAMES);

        let given;
        if (roll < 0.56) {
            given = pick(KOREAN_CURATED_GIVEN);
        } else {
            const f = pick(KOREAN_SYLLABLE_FRONT);
            let b = pick(KOREAN_SYLLABLE_BACK);
            for (let i = 0; i < 6 && b === f; i++) b = pick(KOREAN_SYLLABLE_BACK);
            given = f === b ? pick(KOREAN_CURATED_GIVEN) : `${f}${b}`;
        }
        return `${surname}${given}`;
    }

    function formatName(pool, poolKey) {
        if (poolKey === 'korean') {
            return generateKoreanName();
        }

        // 브라질 일반인식 겹이름 + 성씨 조합 (약 14%)
        if (poolKey === 'brazilian' && Math.random() < 0.14) {
            return `${pick(BRAZILIAN_COMPOUND_GIVEN)} ${pick(pool.family)}`;
        }

        // 스페인/중남미/포르투갈 가끔 이중 성 (이름 + 성1 + 성2)
        if ((poolKey === 'spanish' || poolKey === 'latin_america' || poolKey === 'portuguese') && Math.random() < 0.14) {
            const g = pick(pool.given);
            const f1 = pick(pool.family);
            const f2 = pick(pool.family);
            if (f1 !== f2 && g !== f1 && g !== f2) {
                return `${g} ${f1} ${f2}`;
            }
        }

        // 프랑스 가끔 복합 이름 (장 뤼크 ~, 피에르 알랭 ~ 등)
        if (poolKey === 'french' && Math.random() < 0.08) {
            const firstParts = ['장', '피에르', '폴', '마르크', '샤를', '루이'];
            const secondParts = ['뤼크', '에밀', '앙투안', '알랭', '앙리', '밥티스트'];
            return `${pick(firstParts)} ${pick(secondParts)} ${pick(pool.family)}`;
        }

        const family = pick(pool.family);
        let given = pick(pool.given);
        if (given === family && pool.given.length > 1) {
            for (let i = 0; i < 6 && given === family; i++) {
                given = pick(pool.given);
            }
        }

        if (pool.format === 'korean_no_space') return `${family}${given}`;
        if (pool.format === 'east_asian_space') return `${family} ${given}`;
        return `${given} ${family}`;
    }

    function generateUniqueName(country, existingNames = null) {
        const used = existingNames instanceof Set ? existingNames : collectExistingNames(existingNames);
        const poolKey = getPoolKeyForCountry(country);
        const pool = NAME_POOLS[poolKey] || NAME_POOLS.english;

        for (let attempt = 0; attempt < 120; attempt++) {
            const candidate = formatName(pool, poolKey);
            if (!used.has(candidate)) {
                return candidate;
            }
        }

        const base = formatName(pool, poolKey);
        if (poolKey === 'korean') {
            for (let attempt = 0; attempt < 60; attempt++) {
                const candidate = `${pick(KOREAN_COMMON_SURNAMES)}${pick(KOREAN_SYLLABLE_FRONT)}${pick(KOREAN_SYLLABLE_BACK)}`;
                if (!used.has(candidate)) return candidate;
            }
        } else if (pool.format === 'western') {
            for (let attempt = 0; attempt < 60; attempt++) {
                const g = pick(pool.given);
                const f1 = pick(pool.family);
                const f2 = pick(pool.family);
                if (f1 !== f2 && g !== f1 && g !== f2) {
                    const candidate = `${g} ${f1} ${f2}`;
                    if (!used.has(candidate)) return candidate;
                }
            }
        }

        return base;
    }

    function pickDetailPosition(position) {
        const pos = (position || 'MF').toUpperCase();
        const choices = DETAIL_POSITIONS_BY_POS[pos] || DETAIL_POSITIONS_BY_POS.MF;
        const selected = pickWeighted(choices);
        const otherPositions = [];

        if (selected.others && selected.others.length > 0 && Math.random() < 0.65) {
            const count = Math.random() < 0.7 ? 1 : 2;
            const shuffled = [...selected.others].sort(() => Math.random() - 0.5);
            for (let i = 0; i < Math.min(count, shuffled.length); i++) {
                otherPositions.push(shuffled[i]);
            }
        }

        return { detailPosition: selected.dp, otherPositions };
    }

